// Dynamically compute journey counts for each country and region from the authoritative JOURNEYS list
// This guarantees that journey counts everywhere in UI, pills, pins, and trays ALWAYS match 100%
export const DESTINATION_COUNTRIES: DestinationCountry[] = BASE_COUNTRIES.map((country) => {
  const countryJourneys = JOURNEYS.filter((j) => j.countryId === country.id);
  return {
    ...country,
    journeyCount: countryJourneys.length,
    regions: country.regions.map((reg) => {
      const regJourneys = countryJourneys.filter((j) => j.regionId === reg.id);
      return {
        ...reg,
        journeyCount: regJourneys.length,
      };
    }),
  };
});
